"""Analyse P5 runs: python analyze_p5.py OUTDIR [ORACLE_DIR]

ORACLE_DIR holds the bg-scenario CSVs as <protocol>_oracle.csv (default OUTDIR).
Prints a summary and writes OUTDIR/p5_summary.txt and OUTDIR/p5_lymph.png.
"""

import sys
from pathlib import Path

import numpy as np

OUT = Path(sys.argv[1])
ORACLE = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
PROTOCOLS = ["rest", "rest82", "hemorrhage", "infusion"]
LABELS = {"rest": "rest (shipped state)", "rest82": "rest (state regenerated by 8.2.0)",
          "hemorrhage": "hemorrhage", "infusion": "infusion"}
lines = []


def say(s=""):
    print(s)
    lines.append(s)


def load(path):
    with open(path) as f:
        header = f.readline().strip().split(",")
    data = np.genfromtxt(path, delimiter=",", skip_header=1)
    return header, np.atleast_2d(data)


def at(t, x, when):
    return x[np.argmin(np.abs(t - when))]


def window_mean(t, x, t0, t1):
    m = (t >= t0) & (t <= t1)
    return float(np.mean(x[m]))


runs = {}
for p in PROTOCOLS:
    f = OUT / f"{p}_binding.csv"
    if not f.exists():
        continue
    h, d = load(f)
    runs[p] = {name: d[:, i] for i, name in enumerate(h)}
    r = runs[p]
    r["valves"] = sum(r[k] for k in h if k.endswith("Lymph_mL_per_min"))

say("P5 summary (BioGears 8.2.0, StandardMale@0s, samples every 30 s)")
say("=" * 70)

# 1. Resting flow -----------------------------------------------------------
for rest in [k for k in ("rest", "rest82") if k in runs]:
    r = runs[rest]
    t = r["t_s"]
    say(f"\n1. {LABELS[rest]}, 0-120 min")
    for t0, t1 in [(0, 600), (3000, 3600), (6600, 7200)]:
        ret = window_mean(t, r["LymphReturn_mL_per_min"], t0, t1)
        val = window_mean(t, r["valves"], t0, t1)
        say(f"   {t0/60:5.0f}-{t1/60:<4.0f} min: return to vena cava {ret:5.2f} mL/min = {ret*1.44:4.2f} L/day; "
            f"formation (valves) {val:5.2f} mL/min = {val*1.44:4.2f} L/day")
    v = r["LymphVolume_node_mL"]
    say(f"   lymph pool: {v[0]:.1f} -> {at(t, v, 3600):.1f} (60 min) -> {v[-1]:.1f} mL (120 min); "
        f"pressure {r['LymphPressure_mmHg'][0]:.3f} -> {r['LymphPressure_mmHg'][-1]:.3f} mmHg")
    say(f"   rate of rise, last 30 min: {np.polyfit(t[t >= 5400], v[t >= 5400], 1)[0]*60:.2f} mL/min")
    last = {k[:-len('Lymph_mL_per_min')]: r[k][t >= 6600].mean() for k in r if k.endswith("Lymph_mL_per_min")}
    tot = sum(last.values())
    say("   formation by tissue, last 10 min (mL/min, share):")
    for k, x in sorted(last.items(), key=lambda kv: -kv[1]):
        say(f"     {k:12s} {x:6.3f}  {100*x/tot:4.1f}%")

# 2. Mass balance on the Lymph node (oracle independent of the flow reads) ---
say("\n2. Mass balance on the Lymph node: dV = integral(formation - return) dt")
for p, r in runs.items():
    t = r["t_s"]
    net = r["valves"] - r["LymphReturn_mL_per_min"]
    integ = np.trapezoid(net, t / 60.0)
    dv = r["LymphVolume_node_mL"][-1] - r["LymphVolume_node_mL"][0]
    say(f"   {p:10s}: dV {dv:8.2f} mL; integral {integ:8.2f} mL; "
        f"difference {integ - dv:+.2f} mL ({100*(integ-dv)/abs(dv):+.1f}%; 30-s point samples of pulsatile flows)")
    cm = np.max(np.abs(r["LymphVolume_cmpt_mL"] - r["LymphVolume_node_mL"]))
    say(f"   {'':10s}  max |compartment volume - node volume| = {cm:.2e} mL")

# 3. Oracle: bg-scenario, standard requests ----------------------------------
say("\n3. Binding vs bg-scenario (same protocol, standard requests), max relative difference")
say("   Note: bg-scenario's SEScenarioExec runs each AdvanceTime as `for (i = 0; i <= count; i++)`,")
say("   one extra 0.02 s step, so its actions land 0.02 s later per segment (its log: 300.02 s, 660.04 s).")
say("   With the binding's action moved to 300.02 s, HR and MAP match bg-scenario to ~1e-13 (see README).")
pairs = [("LymphVolume_cmpt_mL", "Lymph-Volume(mL)"), ("BloodVolume_mL", "BloodVolume(mL)"),
         ("ExtravascularFluidVolume_mL", "ExtravascularFluidVolume(mL)"),
         ("MAP_mmHg", "MeanArterialPressure(mmHg)"), ("HR_per_min", "HeartRate(1/min)")]
for p, r in runs.items():
    f = ORACLE / f"{p}_oracle.csv"
    if not f.exists():
        say(f"   {p}: no bg-scenario run")
        continue
    h, d = load(f)
    ot = d[:, 0]
    idx = [int(np.argmin(np.abs(ot - tt))) for tt in r["t_s"][1:]]
    dt = np.max(np.abs(ot[idx] - r["t_s"][1:]))
    parts = []
    for bcol, ocol in pairs:
        o = d[idx, h.index(ocol)]
        b = r[bcol][1:]
        parts.append(f"{bcol.split('_')[0]} {np.max(np.abs(b - o) / np.abs(o)):.1e}")
    say(f"   {p:10s}: " + ", ".join(parts) + f"  (max time offset {dt:.3f} s)")

# 4. Perturbations -------------------------------------------------------------
for p, marks in [("hemorrhage", [(300, "pre-bleed"), (660, "bleed stops"), (1800, "30 min"), (3900, "65 min")]),
                 ("infusion", [(300, "pre-infusion"), (900, "infusion ends"), (1800, "30 min"), (3900, "65 min")])]:
    if p not in runs:
        continue
    r = runs[p]
    t = r["t_s"]
    say(f"\n4. {p}")
    say("   time          return   formation  pool      blood vol  extravasc.  MAP    HR")
    say("   (min)         mL/min   mL/min     mL        mL         mL          mmHg   /min")
    for when, label in marks:
        w = (t >= when - 120) & (t <= when)  # 2-min mean before the mark smooths pulsatility
        m = lambda k: r[k][w].mean()
        say(f"   {when/60:5.1f} {label:14s} {m('LymphReturn_mL_per_min'):5.2f}   {r['valves'][w].mean():5.2f}   "
            f"{m('LymphVolume_node_mL'):8.1f}  {m('BloodVolume_mL'):7.0f}    {m('ExtravascularFluidVolume_mL'):7.0f}   "
            f"{m('MAP_mmHg'):5.1f}  {m('HR_per_min'):5.1f}")

(OUT / "p5_summary.txt").write_text("\n".join(lines) + "\n")

# Figure -------------------------------------------------------------------------
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    sys.exit(0)

fig, axes = plt.subplots(3, len(runs), figsize=(4.2 * len(runs), 8), sharex="col", squeeze=False)
for j, (p, r) in enumerate(runs.items()):
    t = r["t_s"] / 60
    k = 4  # 2-min moving mean for the pulsatile flows (t = 0 is the loaded state, before any step)
    sm = lambda x: np.convolve(x[1:], np.ones(k) / k, mode="valid")
    ts = t[1:][k - 1:]
    ax = axes[0, j]
    ax.plot(ts, sm(r["valves"]), label="formation (13 valves)")
    ax.plot(ts, sm(r["LymphReturn_mL_per_min"]), label="return to vena cava")
    ax.axhspan(2000 / 1440, 4000 / 1440, color="0.85", label="2-4 L/day")
    ax.set_title(LABELS[p], fontsize=10)
    ax.set_ylabel("lymph flow (mL/min)")
    axes[1, j].plot(t, r["LymphVolume_node_mL"])
    axes[1, j].set_ylabel("lymph pool (mL)")
    axes[2, j].plot(t, r["BloodVolume_mL"], label="blood")
    axes[2, j].plot(t, r["ExtravascularFluidVolume_mL"] - r["ExtravascularFluidVolume_mL"][0] + r["BloodVolume_mL"][0],
                    label="extravascular (shifted)")
    axes[2, j].set_ylabel("volume (mL)")
    axes[2, j].set_xlabel("time (min)")
axes[0, 0].legend(fontsize=7)
axes[2, 0].legend(fontsize=7)
fig.tight_layout()
fig.savefig(OUT / "p5_lymph.png", dpi=120)
